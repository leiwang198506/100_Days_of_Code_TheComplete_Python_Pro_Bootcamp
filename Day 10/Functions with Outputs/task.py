def format_name(f_name, l_name):
    """
    This is the documentation,hahaha.
    :param f_name: first names
    :param l_name: last names
    :return: the title case version of the names
    """

    f_name_title=f_name.title()
    l_name_title =l_name.title()
    # print(f"{f_name_title} {l_name_title}")
    return f"{f_name_title} {l_name_title}"

